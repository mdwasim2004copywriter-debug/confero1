def _is_low_quality_phrase(term):
    words = term.split()
    if words[0] in BAD_PHRASE_EDGE_WORDS or words[-1] in BAD_PHRASE_EDGE_WORDS:
        return True
    if len(words) == 2 and len(words[0]) >= 4 and words[0][:4] == words[1][:4]:
        return True
    if all(w in _WEEKDAYS_MONTHS for w in words):
        return True
    if all(w in FILLER_WORDS or w in GENERIC_SINGLE_WORDS for w in words):
        return True
    if any(w.isdigit() for w in words) and len(words) <= 2:
        return True  # a bare number (with at most one modifier) isn't a topic
    return False


def _ranked_ngrams(sentences, ngram_range, max_features):
    try:
        vectorizer = TfidfVectorizer(stop_words="english", ngram_range=ngram_range, max_features=max_features)
        tfidf = vectorizer.fit_transform(sentences)
        scores = np.asarray(tfidf.sum(axis=0)).flatten()
        terms = vectorizer.get_feature_names_out()
        return [t for t, _ in sorted(zip(terms, scores), key=lambda x: -x[1])]
    except Exception:
        return []


def _frequency_fallback_topics(text):
    words = [w for w in re.findall(r"[a-zA-Z]{5,}", text.lower()) if w not in STOPWORDS and w not in GENERIC_SINGLE_WORDS]
    return [w.capitalize() for w, _ in Counter(words).most_common(8)]


def extract_topics(sentences, limit=8):
    if len(sentences) < 2:
        return _frequency_fallback_topics(" ".join(sentences))

    full_text_words = Counter(re.findall(r"[a-z']+", " ".join(sentences).lower()))

    phrase_terms = [t for t in _ranked_ngrams(sentences, (2, 3), 50) if not _is_low_quality_phrase(t)]
    # Repetition bonus: a phrase whose head content word recurs elsewhere in
    # the transcript (even outside this exact n-gram) is more likely a real
    # topic than a one-off phrase -- re-rank with that as a tiebreaker.
    phrase_terms.sort(key=lambda t: -sum(full_text_words[w] for w in t.split() if w not in STOPWORDS))
    phrase_terms.sort(key=lambda t: any(w in _WEEKDAYS_MONTHS for w in t.split()))  # dates deprioritized, stable sort

    single_terms = [
        t for t in _ranked_ngrams(sentences, (1, 1), 30)
        if t not in GENERIC_SINGLE_WORDS and len(t) > 4 and full_text_words[t] >= 2
    ]

    kept = []
    for term in phrase_terms:
        if any(term != k and term in k for k in kept):
            continue
        kept = [k for k in kept if not (k != term and k in term)]
        kept.append(term)

    for term in single_terms:
        if len(kept) >= limit:
            break
        if any(term in k for k in kept):
            continue
        kept.append(term)

    topics = [t.title() for t in kept[:limit]]
    if len(topics) < 3:
        extra = [t for t in _frequency_fallback_topics(" ".join(sentences)) if t not in topics]
        topics = (topics + extra)[:limit]
    return topics


