"""
Meeting intelligence V2, relationship-based transcript understanding, no
external LLM.

V1 treated the transcript as: sentences -> important words -> important
sentences -> templates. That's why it produced failures like "We haven't
decided..." being classified as a decision, or numbers being dumped without
context. V2 changes the architecture to:

    transcript -> utterances -> classified linguistic events
               -> semantic relations (decision/proposal/action, deadline
                  original->revised, problem->evidence->priority,
                  question->answer/unresolved)
               -> a lightweight Meeting State (the extracted dict this
                  module returns) -> validation -> composed report text

Every structured item is still either a literal transcript excerpt or a
mechanical transformation of one (prefix-stripping, template composition
over already-extracted fields), nothing is generated by a language model,
so nothing here can hallucinate a decision/action/deadline/fact that wasn't
actually said. Where the text IS transformed (action-item normalization,
purpose/summary/conclusion composition), the transformation is a fixed,
inspectable rule, not free-form generation.

Deliberate scope limits (see the "do not overengineer" note in the spec
this was built against): only the utterance types that are actually
extracted into a report section are classified (fact/question/answer/
proposal/decision/action/problem/deadline/unresolved). Types like
greeting/clarification/correction/disagreement aren't modeled as separate
outputs, there's no report section that would use them, and building
detectors nothing consumes is exactly the overengineering to avoid.
"""

import re
from collections import Counter

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

# =======================================================================
# Shared primitives
# =======================================================================

_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+")


def split_sentences(text):
    return [s.strip() for s in _SENTENCE_SPLIT.split(text) if s.strip()]


STOPWORDS = frozenset(
    "a an the this that these those i you he she it we they me him her us them "
    "my your his its our their is am are was were be been being have has had "
    "do does did will would shall should can could may might must "
    "and or but if because as until while of at by for with about against "
    "between into through during before after above below to from up down in "
    "out on off over under again further then once here there when where why "
    "how all any both each few more most other some such no nor not only own "
    "same so than too very just also".split()
)

GENERIC_SINGLE_WORDS = frozenset(
    "think understand words system good know yeah okay right going really "
    "actually guess kind sort thing things stuff want need like well just "
    "very much also even still then here there getting got make made way "
    "look looking said say says something someone anything everything sure "
    "records issue final".split()
)

FILLER_WORDS = frozenset("um uh umm uhh like yeah okay ok right so well".split())
BAD_PHRASE_EDGE_WORDS = frozenset("let lets say says going talk want wants ll ve re did does".split())
_WEEKDAYS_MONTHS = frozenset(
    "monday tuesday wednesday thursday friday saturday sunday january february march "
    "april may june july august september october november december".split()
)


def _word_set(text):
    return {w for w in re.findall(r"[a-z']+", text.lower()) if w not in STOPWORDS and len(w) > 2}


def _jaccard(a, b):
    if not a or not b:
        return 0.0
    union = len(a | b)
    return len(a & b) / union if union else 0.0


def dedupe_by_similarity(items, key, threshold=0.6, limit=None):
    kept, kept_sets = [], []
    for item in items:
        s = _word_set(key(item))
        if any(_jaccard(s, k) >= threshold for k in kept_sets):
            continue
        kept.append(item)
        kept_sets.append(s)
        if limit and len(kept) >= limit:
            break
    return kept


def _speaker_label(speakers, speaker_id):
    for s in speakers:
        if s["id"] == speaker_id:
            return s["label"]
    return speaker_id


def build_utterances(transcript, speakers):
    utterances = []
    idx = 0
    for seg in transcript:
        label = _speaker_label(speakers, seg["speakerId"])
        for sent in split_sentences(seg["text"]):
            utterances.append(
                {
                    "id": idx,
                    "text": sent,
                    "lower": sent.lower(),
                    "speaker_id": seg["speakerId"],
                    "speaker_label": label,
                    "start": seg["start"],
                    "end": seg["end"],
                }
            )
            idx += 1
    return utterances


def _centrality_scores(sentences):
    n = len(sentences)
    if n == 0:
        return []
    if n == 1:
        return [1.0]
    try:
        vectorizer = TfidfVectorizer(stop_words="english")
        tfidf = vectorizer.fit_transform(sentences)
        sim = cosine_similarity(tfidf)
        np.fill_diagonal(sim, 0)
        row_sums = sim.sum(axis=1, keepdims=True)
        row_sums[row_sums == 0] = 1
        transition = sim / row_sums
        scores = np.ones(n) / n
        damping = 0.85
        for _ in range(30):
            scores = (1 - damping) / n + damping * transition.T.dot(scores)
        return scores.tolist()
    except Exception:
        return [0.0] * n


# =======================================================================
# Negation / hedge / commitment vocabulary
# =======================================================================
# This is the fix for the single biggest V1 failure class: a sentence
# containing "decided"/"agreed"/etc. inside an EXPLICIT NEGATION ("haven't
# decided") must never reach the decision classifier at all -- it's routed
# to the open-question/unresolved engine instead, unconditionally.

UNRESOLVED_MARKERS = [
    "haven't decided", "have not decided", "haven't agreed", "have not agreed",
    "not decided", "not sure", "not certain", "unsure", "uncertain", "undecided",
    "unresolved", "pending", "still need to decide", "still deciding",
    "need to discuss", "needs to be discussed", "haven't figured out",
    "don't know yet", "not convinced", "no consensus", "haven't confirmed",
    "not finalized", "not final yet", "yet to decide", "haven't chosen",
    "not chosen", "up in the air", "haven't settled",
]

# Hedges: presence of one of these means the sentence is an OPINION/PROPOSAL
# at most, never a decision, regardless of what other markers it contains.
HEDGE_MARKERS = [
    "i think", "i guess", "maybe", "perhaps", "possibly", "probably",
    "i'm not sure", "i am not sure", "not entirely sure", "i suppose",
    "i would think", "my guess is", "i'd say",
]

# Strong, explicit commitment/agreement language -- always a decision unless
# hedged or unresolved.
AGREEMENT_MARKERS = [
    "we've agreed", "we have agreed", "agreed to", "we agreed", "decided to",
    "we've decided", "we have decided", "the team decided", "confirmed that",
    "approved", "final decision", "settled on", "locked to", "locked in",
    "signed off", "concluded that",
]

# Weaker, GROUP-scoped commitment markers ("we"/"let's") -- a decision only
# when not hedged and not just conversational scene-setting (meta-verb check).
COMMIT_MARKERS = ["we will", "we'll", "let's", "we're going to", "we should"]

# Bare suggestion language -- on its own, per the spec, this is only ever a
# signal, never proof of a decision.
SOFT_SIGNAL_MARKERS = ["should", "need to", "want to", "plan to", "could", "might"]

_META_VERB_AFTER_COMMITMENT = re.compile(
    r"\b(?:let's|we'll|we will|we're going to|we should)\s+(?:just\s+)?"
    r"(try|talk\s+about|begin|continue|move\s+on|go\s+over|look\s+at|discuss|practice|make\s+it)\b",
    re.IGNORECASE,
)

_ILLUSTRATIVE_CONDITIONAL = ("if i say", "if you say", "imagine that", "imagine you", "suppose ", "what if")


def is_unresolved(lower):
    return any(m in lower for m in UNRESOLVED_MARKERS)


def _is_meta(lower):
    return bool(_META_VERB_AFTER_COMMITMENT.search(lower))


def _is_illustrative_example(lower):
    return any(lower.startswith(p) for p in _ILLUSTRATIVE_CONDITIONAL)


_CONDITIONAL_CLAUSE = re.compile(r"^(?:if|unless)\s+(.+?),\s*(.+)$", re.IGNORECASE)


def split_conditional(text):
    """'If the accuracy is low, I'll rerun it.' -> ('the accuracy is low', "I'll rerun it.")"""
    m = _CONDITIONAL_CLAUSE.match(text.strip())
    if not m:
        return None, text
    return m.group(1).strip(), m.group(2).strip()


# =======================================================================
# Decisions vs. proposals (the core V1 -> V2 correction)
# =======================================================================


def classify_commitment(text, lower):
    """Returns ('decision'|'proposal', confidence, reason) or None.

    Decision requires either an explicit agreement marker, or a group
    commitment marker ("let's"/"we'll") with NO hedge and no meta/
    conversational verb. A hedge ("I think", "maybe") caps it at proposal
    regardless of what other markers are present -- this is what correctly
    separates "Let's move the deadline" (decision) from "I think we should
    move the deadline" (proposal), per the spec's own worked example.
    """
    if lower.endswith("?") or _is_illustrative_example(lower) or is_unresolved(lower):
        return None

    has_hedge = any(h in lower for h in HEDGE_MARKERS)
    has_agreement = any(m in lower for m in AGREEMENT_MARKERS)
    has_commit = any(m in lower for m in COMMIT_MARKERS) and not _is_meta(lower)
    has_soft = any(m in lower for m in SOFT_SIGNAL_MARKERS)

    if has_agreement and not has_hedge:
        return ("decision", 0.9, "explicit agreement/commitment marker")
    if has_commit and not has_hedge:
        return ("decision", 0.65, "group commitment marker (let's/we'll), no hedge")
    if has_hedge and (has_commit or has_soft):
        return ("proposal", 0.55, "hedge marker + suggestion marker")
    if has_soft and not has_hedge and not has_commit and re.match(r"^(we|the team)\b", lower):
        return ("proposal", 0.4, "bare group suggestion marker, no commitment/hedge")
    return None


def extract_decisions_and_proposals(utterances, limit=6):
    decisions, proposals = [], []
    for u in utterances:
        result = classify_commitment(u["text"], u["lower"])
        if not result:
            continue
        kind, confidence, reason = result
        item = {
            "text": u["text"],
            "speaker": u["speaker_label"],
            "confidence": "high" if confidence >= 0.8 else "medium",
            "reason": reason,
            "source_ids": [u["id"]],
        }
        (decisions if kind == "decision" else proposals).append((confidence, item))

    decisions.sort(key=lambda t: -t[0])
    proposals.sort(key=lambda t: -t[0])
    decisions = dedupe_by_similarity([d for _, d in decisions], key=lambda d: d["text"], threshold=0.6, limit=limit)
    proposals = dedupe_by_similarity([p for _, p in proposals], key=lambda p: p["text"], threshold=0.6, limit=limit)
    return decisions, proposals


# =======================================================================
# Actions: first-person / group / conditional, with text normalization
# =======================================================================

ACTION_FIRST_PERSON = ["i'll", "i will", "i can", "i'm going to", "i am going to", "i plan to", "i need to", "i have to", "let me"]
ACTION_GROUP = ["we need to", "we have to", "we'll", "we will", "we're going to", "let's", "we must"]
ACTION_DIRECTED = ["can you", "could you", "someone needs to", "we need someone to"]
ACTION_VERBS = [
    "review", "follow up", "test", "compare", "calculate", "investigate",
    "prepare", "send", "update", "verify", "implement", "check", "finalize",
    "own", "flag", "confirm", "report", "reach out", "put together", "schedule",
    "organize", "draft", "write", "build", "fix", "research", "look into",
    "rerun", "re-run", "redo", "retry", "validate", "optimize", "refactor",
    "deploy", "release", "migrate", "clean", "document", "design", "analyze",
]

_DUE_DATE_PATTERN = re.compile(
    r"\b(?:by\s+)?(?:tomorrow|today|tonight|end\s+of\s+(?:day|week|month))\b"
    r"|\bnext\s+(?:monday|tuesday|wednesday|thursday|friday|saturday|sunday|week|month)\b"
    r"|\b(?:by\s+)?(?:monday|tuesday|wednesday|thursday|friday|saturday|sunday)\b"
    r"|\b(?:by\s+)?(?:january|february|march|april|may|june|july|august|september|october|november|december)"
    r"(?:\s+\d{1,2}(?:st|nd|rd|th)?)?\b"
    r"|\b(?:on\s+)?the\s+\d{1,2}(?:st|nd|rd|th)\b",
    re.IGNORECASE,
)


def extract_due_hint(text):
    match = _DUE_DATE_PATTERN.search(text)
    return match.group(0).strip().capitalize() if match else None


_LEADING_SEQUENCE = re.compile(r"^(?:first|second|third|fourth|next|then|after that|finally|also|now)[,:]?\s+", re.IGNORECASE)
_LEADING_COMMITMENT = re.compile(
    r"^(?:i need to|i have to|i'll|i will|i'm going to|i am going to|i plan to|"
    r"we need to|we have to|we'll|we will|we're going to|let's|let us)\s+",
    re.IGNORECASE,
)
_AND_SPLIT = re.compile(
    r"^(.*?)\band\s+(?:i'll\s+|i will\s+|we'll\s+|we will\s+)?(" + "|".join(re.escape(v) for v in ACTION_VERBS) + r")\b(.*)$",
    re.IGNORECASE,
)


def _finish_clause(clause):
    clause = clause.strip().rstrip(".").strip()
    if not clause:
        return clause
    clause = clause[0].upper() + clause[1:]
    return clause + "."


def normalize_action_text(raw_text):
    """Never show a raw first-person transcript sentence as an action item:
    strip leading discourse markers ("First,") and the commitment phrase
    itself ("I need to"), leaving a plain imperative. Every remaining word
    is still literally from the transcript -- this is prefix-stripping and
    re-casing, not generation. Splits a compound "X and Y" into two action
    items when Y also starts with a recognized action verb."""
    text = _LEADING_SEQUENCE.sub("", raw_text.strip())
    text = _LEADING_COMMITMENT.sub("", text)

    m = _AND_SPLIT.match(text)
    if m and len(m.group(1).split()) >= 2:
        return [_finish_clause(m.group(1)), _finish_clause(m.group(2) + m.group(3))]
    return [_finish_clause(text)]


def extract_action_items(utterances, limit=8):
    candidates, seen = [], set()
    for u in utterances:
        text, lower = u["text"], u["lower"]
        if lower.endswith("?") or text in seen or is_unresolved(lower) or _is_illustrative_example(lower):
            continue

        condition, consequent = split_conditional(text)
        check_text = consequent if condition else text
        check_lower = check_text.lower()

        owner, confidence = None, 0.6
        if any(m in check_lower for m in ACTION_FIRST_PERSON):
            owner, confidence = u["speaker_label"], 0.8
        elif any(m in check_lower for m in ACTION_GROUP) and not _is_meta(check_lower):
            owner, confidence = "Unknown", 0.55
        elif any(m in check_lower for m in ACTION_DIRECTED):
            owner, confidence = "Unknown", 0.55

        if owner is None:
            continue

        has_verb = any(v in check_lower for v in ACTION_VERBS)
        if owner == "Unknown" and not has_verb:
            continue  # directed/group phrasing alone, no concrete verb -- too weak a signal

        seen.add(text)
        for normalized in normalize_action_text(consequent if condition else text):
            candidates.append(
                {
                    "owner": owner,
                    "task": normalized,
                    "due": extract_due_hint(text),
                    "condition": condition,
                    "confidence": "high" if confidence >= 0.75 else "medium",
                    "source_ids": [u["id"]],
                }
            )

    return dedupe_by_similarity(candidates, key=lambda a: a["task"], threshold=0.7, limit=limit)


# =======================================================================
# Deadline relationship engine: original -> revised, with condition
# =======================================================================

ORIGINAL_MARKERS = ["originally", "at first", "initially", "the original plan", "we planned to", "was supposed to", "was originally"]
REVISED_MARKERS = [
    "revised", "instead", "better target", "new deadline", "push", "move it to",
    "move the deadline", "extend", "updated target", "new target", "now targeting",
    "let's target", "propose", "a better target", "realistic target",
]
REJECTION_MARKERS = ["not realistic", "no longer realistic", "won't work", "too tight", "not going to happen", "unrealistic", "isn't going to work", "not feasible", "isn't realistic"]
# Catches the more natural "I don't think that's realistic anymore" phrasing,
# where the negation ("don't think") sits several words before the word it
# actually negates ("realistic") rather than immediately next to it.
_REJECTION_NEGATION = re.compile(r"\b(?:don't|doesn't|isn't|won't|not)\b.{0,25}\b(?:realistic|feasible|going to happen)\b", re.IGNORECASE)


def _has_rejection_signal(lower):
    return any(m in lower for m in REJECTION_MARKERS) or bool(_REJECTION_NEGATION.search(lower))
CONDITION_MARKERS = ["assuming", "provided that", "as long as", "conditional on", "depending on", "once we", "if we can", "if we"]

_DATE_PATTERN = re.compile(
    r"\b\d{4}-\d{2}-\d{2}"
    r"|\b(?:january|february|march|april|may|june|july|august|september|october|november|december)"
    r"\s+\d{1,2}(?:st|nd|rd|th)?(?:,?\s*\d{4})?\b"
    r"|\b\d{1,2}(?:st|nd|rd|th)?\s+(?:january|february|march|april|may|june|july|august|september|october|november|december)\b"
    r"|\b(?:monday|tuesday|wednesday|thursday|friday|saturday|sunday)\b"
    r"|\b\d{1,2}:\d{2}\s?(?:am|pm)?\b",
    re.IGNORECASE,
)


def _extract_condition_clause(text):
    lower = text.lower()
    for marker in CONDITION_MARKERS:
        idx = lower.find(marker)
        if idx != -1:
            clause = text[idx:].strip().rstrip(".")
            return clause
    return None


def extract_timeline(utterances):
    """Builds original->revised deadline relationships instead of a flat
    date list. A date is "original" if it or a nearby earlier utterance
    uses an original-plan marker; "revised" if it or a nearby utterance
    uses a revision marker, or it follows an utterance rejecting an earlier
    date as unrealistic. Anything else is a plain "mentioned" date (goes to
    facts.dates instead of the timeline)."""
    timeline, mentioned_dates, rejection_ids = [], [], []
    rejection_seen_at = None

    for i, u in enumerate(utterances):
        lower = u["lower"]
        if _has_rejection_signal(lower):
            rejection_seen_at = i
            rejection_ids.append(u["id"])

        dates = _DATE_PATTERN.findall(u["text"])
        if not dates:
            continue

        window = " ".join(x["lower"] for x in utterances[max(0, i - 1) : i + 1])
        is_original = any(m in window for m in ORIGINAL_MARKERS)
        is_revised = any(m in window for m in REVISED_MARKERS) or (
            rejection_seen_at is not None and i - rejection_seen_at <= 2
        )

        for date in dates:
            if date.lower() in _WEEKDAYS_MONTHS:
                continue  # bare weekday alone isn't a project deadline
            if is_original and not is_revised:
                timeline.append(
                    {"type": "original", "date": date, "condition": None, "confidence": "high", "source_ids": [u["id"]]}
                )
            elif is_revised:
                condition = _extract_condition_clause(u["text"]) or _extract_condition_clause(
                    utterances[i + 1]["text"] if i + 1 < len(utterances) else ""
                )
                timeline.append(
                    {
                        "type": "revised",
                        "date": date,
                        "condition": condition,
                        "confidence": "medium",
                        "source_ids": [u["id"]],
                    }
                )
            else:
                mentioned_dates.append(date)

    return timeline, mentioned_dates, rejection_ids


# =======================================================================
# Open questions / unresolved items
# =======================================================================

_TRIVIAL_QUESTION_ENDERS = ("right?", "okay?", "ok?", "yeah?", "isn't it?", "you know?", "huh?")


def extract_questions(utterances, limit=5):
    """Merges two sources of "unresolved": literal questions with no
    follow-up answer, AND declarative unresolved statements ("We haven't
    decided whether...") which carry no question mark at all but are just
    as clearly an open item -- V1 only looked for '?', which is exactly why
    an explicit unresolved statement was reported as "no open questions"."""
    scored = []
    for i, u in enumerate(utterances):
        text, lower = u["text"], u["lower"]
        if text.endswith("?"):
            if any(lower.endswith(t) for t in _TRIVIAL_QUESTION_ENDERS):
                continue
            content_words = _word_set(text)
            if len(content_words) < 2:
                continue
            score = len(content_words) + (2 if i == 0 or utterances[i - 1]["speaker_id"] != u["speaker_id"] else 0)
            scored.append((score, i, u, False))
        elif is_unresolved(lower):
            scored.append((len(_word_set(text)) + 3, i, u, True))

    scored.sort(key=lambda t: -t[0])

    important, open_items = [], []
    for _score, i, u, is_declarative in scored:
        if is_declarative:
            open_items.append(u["text"])
            continue
        collected, answer_speaker = [], None
        for j in range(i + 1, min(i + 7, len(utterances))):
            cand = utterances[j]
            if cand["speaker_id"] == u["speaker_id"]:
                break
            if answer_speaker is None:
                answer_speaker = cand["speaker_id"]
            elif cand["speaker_id"] != answer_speaker:
                break
            collected.append(cand["text"])
        combined = " ".join(collected).strip()
        if len(combined.split()) >= 3:
            important.append({"question": u["text"], "answer": combined, "speaker": u["speaker_label"]})
        else:
            open_items.append(u["text"])

    important = dedupe_by_similarity(important, key=lambda q: q["question"], threshold=0.6, limit=limit)
    open_items = dedupe_by_similarity(open_items, key=lambda q: q, threshold=0.6, limit=limit)
    return important, open_items


# =======================================================================
# Problems: problem vs. evidence, plus priority
# =======================================================================

ISSUE_MARKERS = [
    # More specific/descriptive markers are listed first -- extract_issues
    # takes the FIRST match, so this ordering prefers a concrete label
    # ("incorrect values") over a generic one ("problem") when a sentence
    # contains both.
    "incorrect values", "incorrect", "inaccurate", "missing", "stale data",
    "wrong", "mistake", "bug", "blocker", "blocking", "error", "failure",
    "failed", "fail", "confus", "misunderstand", "couldn't", "can't",
    "cannot", "unable", "limitation", "concern", "unclear",
    "doesn't work", "didn't work", "hard to", "struggl",
    "difficulty", "difficult", "challenge", "problem", "issue",
]
# A negative-sounding marker inside one of these softened frames isn't a
# standalone problem -- it's context/evidence about something else ("the
# calculation isn't NECESSARILY wrong" is a hedge, not a problem report).
SOFTENED_NEGATIVE = ["isn't necessarily", "is not necessarily", "not necessarily", "doesn't have to be", "not always", "not that big of a deal", "not a huge deal"]

PRIORITY_HIGH = ["biggest problem", "main issue", "immediate priority", "critical", "urgent", "most important", "top priority", "highest priority", "before anything else", "primary blocker", "primary concern"]
PRIORITY_LOW = ["less important", "optional", "if possible", "later", "next version", "lower priority", "not as important", "less critical", "less urgent"]

_COMPARATIVE_PRIORITY = re.compile(
    r"(.+?)\s+is\s+(?:probably|generally|definitely|clearly)?\s*(less|more)\s+important\s+than\s+(.+)",
    re.IGNORECASE,
)


def extract_issues(utterances, limit=6, exclude_ids=frozenset()):
    candidates, seen = [], set()
    for i, u in enumerate(utterances):
        text, lower = u["text"], u["lower"]
        if lower.endswith("?") or text in seen or u["id"] in exclude_ids:
            continue
        if any(s in lower for s in SOFTENED_NEGATIVE):
            continue  # hedge/context, not a standalone problem claim
        matched = next((m for m in ISSUE_MARKERS if m in lower), None)
        if not matched:
            continue
        seen.add(text)

        window = " ".join(x["lower"] for x in utterances[max(0, i - 1) : i + 2])
        if any(m in window for m in PRIORITY_HIGH):
            priority = "high"
        elif any(m in window for m in PRIORITY_LOW):
            priority = "low"
        else:
            priority = "medium"

        candidates.append({"issue": matched.strip().capitalize(), "evidence": text, "priority": priority, "source_ids": [u["id"]]})

    priority_rank = {"high": 0, "medium": 1, "low": 2}
    candidates.sort(key=lambda c: priority_rank[c["priority"]])
    return dedupe_by_similarity(candidates, key=lambda i: i["evidence"], threshold=0.6, limit=limit)


def extract_priority_relations(utterances):
    """Direct comparative statements ("X is less important than Y") --
    used to order issues/conclusion text, not a full priority graph solver."""
    relations = []
    for u in utterances:
        m = _COMPARATIVE_PRIORITY.search(u["text"])
        if not m:
            continue
        subject, direction, other = m.group(1).strip(), m.group(2).lower(), m.group(3).strip().rstrip(".")
        higher, lower = (other, subject) if direction == "less" else (subject, other)
        relations.append((higher, lower))
    return relations


