def build_speaker_insights(speakers, utterances, decisions, proposals, actions, issues, questions):
    insights = []
    for sp in speakers:
        sp_ids = {u["id"] for u in utterances if u["speaker_id"] == sp["id"]}
        if not sp_ids:
            continue

        their_issues = [i for i in issues if set(i["source_ids"]) & sp_ids]
        their_decisions = [d for d in decisions if d["speaker"] == sp["label"]]
        their_proposals = [p for p in proposals if p["speaker"] == sp["label"]]
        their_actions = [a for a in actions if a["owner"] == sp["label"]]
        their_questions = [q for q in questions if q["speaker"] == sp["label"]]

        parts = []
        if their_issues:
            top = their_issues[0]
            parts.append(f"identified {top['issue'].lower()} as a {top['priority']}-priority issue")
        if their_proposals:
            parts.append(f"proposed {len(their_proposals)} idea{'s' if len(their_proposals) != 1 else ''}")
        if their_decisions:
            parts.append(f"was involved in {len(their_decisions)} decision{'s' if len(their_decisions) != 1 else ''}")
        if their_actions:
            parts.append(f"owns {len(their_actions)} action item{'s' if len(their_actions) != 1 else ''}")
        if their_questions:
            parts.append(f"raised {len(their_questions)} notable question{'s' if len(their_questions) != 1 else ''}")

        summary = f"{sp['label']} {_join(parts)}." if parts else f"{sp['label']} contributed to the discussion without any decisions, actions, or issues directly attributed to them."

        insights.append(
            {
                "id": sp["id"],
                "label": sp["label"],
                "summary": summary,
                "contributions": [i["evidence"] for i in their_issues[:2]] or [d["text"] for d in their_decisions[:2]],
                "questionsRaised": [q["question"] for q in their_questions[:2]],
                "decisionsOrActions": [d["text"] for d in their_decisions[:2]] + [a["task"] for a in their_actions[:2]],
            }
        )
    return insights


