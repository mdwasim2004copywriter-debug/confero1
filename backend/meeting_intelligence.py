def _empty_notes():
    return {
        "summary": "No speech detected.",
        "purpose": "Not enough speech to determine a purpose.",
        "topics": [],
        "takeaways": [],
        "decisions": [],
        "proposals": [],
        "actionItems": [],
        "questions": [],
        "openQuestions": [],
        "issues": [],
        "facts": {"numbers": [], "dates": [], "technicalTerms": []},
        "timeline": [],
        "speakerInsights": [],
        "conclusion": "No conclusion available, no speech was detected in this recording.",
    }


def analyze_transcript(transcript, speakers, meeting_type=None):
    text = " ".join(seg["text"] for seg in transcript)
    if not text.strip():
        return _empty_notes()

    utterances = build_utterances(transcript, speakers)
    sentences = [u["text"] for u in utterances]
    centrality = _centrality_scores(sentences)

    decisions, proposals = extract_decisions_and_proposals(utterances)
    actions = extract_action_items(utterances)
    important_questions, open_questions = extract_questions(utterances)
    timeline, mentioned_dates, rejection_ids = extract_timeline(utterances)
    timeline_ids = {sid for t in timeline for sid in t["source_ids"]} | set(rejection_ids)
    issues = extract_issues(utterances, exclude_ids=timeline_ids)
    numbers, extra_dates = extract_facts(utterances)
    dates = list(dict.fromkeys(mentioned_dates + extra_dates))
    topics = extract_topics(sentences)
    technical_terms = extract_technical_terms(utterances, exclude=topics + dates)
    priority_relations = extract_priority_relations(utterances)

    decisions, actions, topics, open_questions = validate_state(decisions, actions, topics, open_questions)

    word_total = len(re.findall(r"[a-zA-Z']+", text))
    primary, secondary, purpose_confidence, purpose_evidence = infer_purpose(
        text.lower(), word_total, issues, actions, timeline, open_questions
    )

    takeaways = extract_takeaways(utterances, centrality, issues, actions, timeline, open_questions, decisions)
    speaker_insights = build_speaker_insights(speakers, utterances, decisions, proposals, actions, issues, important_questions)

    return {
        "summary": compose_executive_summary(primary, secondary, topics, decisions, actions, issues, timeline, open_questions),
        "purpose": compose_purpose(primary, secondary, topics),
        "topics": topics,
        "takeaways": takeaways,
        "decisions": decisions,
        "proposals": proposals,
        "actionItems": actions,
        "questions": important_questions,
        "openQuestions": open_questions,
        "issues": issues,
        "facts": {"numbers": numbers, "dates": dates, "technicalTerms": technical_terms},
        "timeline": timeline,
        "speakerInsights": speaker_insights,
        "conclusion": compose_conclusion(issues, actions, timeline, open_questions, priority_relations),
    }
