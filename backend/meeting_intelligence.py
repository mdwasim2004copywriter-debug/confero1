# Facts: numbers/dates with semantic context, technical terms
# =======================================================================

_NUMBER_PATTERN = re.compile(
    r"\b\d+(?:,\d{3})*(?:\.\d+)?\s?(?:%|percent|degrees?|°[CF]?)\b"
    r"|\b\d+\.\d+\b"
    r"|\b\d{2,}(?:,\d{3})*\b"
)


_WORD_WITH_CONTRACTION = re.compile(r"[a-zA-Z]+(?:'[a-zA-Z]+)?")
# "3 of 5 planned user roles" -- a ratio like this is clearly meaningful
# regardless of digit count, so it gets its own pattern rather than relying
# on _NUMBER_PATTERN (which requires 2+ digits for a bare number, to avoid
# matching stray single digits elsewhere in ordinary speech).
_RATIO_PATTERN = re.compile(r"\b(\d+)\s+of\s+(?:the\s+)?(\d+)\s+([a-zA-Z]+(?:\s+[a-zA-Z]+){0,2})", re.IGNORECASE)


def extract_facts(utterances, limit=8):
    numbers, seen_n = [], set()
    for u in utterances:
        text = u["text"]
        date_spans = [m.span() for m in _DATE_PATTERN.finditer(text)]
        ratio_spans = []

        for m in _RATIO_PATTERN.finditer(text):
            noun = " ".join(w for w in m.group(3).split() if w.lower() not in STOPWORDS)
            val = f"{m.group(1)} of {m.group(2)} {noun}".strip()
            if val.lower() not in seen_n:
                seen_n.add(val.lower())
                numbers.append(val)
            ratio_spans.append(m.span())

        for m in _NUMBER_PATTERN.finditer(text):
            if any(s <= m.start() < e for s, e in ratio_spans):
                continue  # already captured as part of a ratio above
            val = m.group(0).strip()
            start, end = m.span()
            if val in seen_n or any(start >= ds and end <= de for ds, de in date_spans):
                continue  # already covered by a date (e.g. the "28" in "August 28")

            # Word-boundary-safe context window: extend outward to whitespace
            # so a label is never truncated mid-word.
            before_start = max(0, start - 40)
            while before_start > 0 and text[before_start].isalpha():
                before_start -= 1
            after_end = min(len(text), end + 40)
            while after_end < len(text) and text[after_end].isalpha():
                after_end += 1

            before = _WORD_WITH_CONTRACTION.findall(text[before_start:start])
            after = _WORD_WITH_CONTRACTION.findall(text[end:after_end])
            after = [w for w in after if w.lower() not in STOPWORDS and len(w) > 1][:3]
            before = [w for w in before if w.lower() not in STOPWORDS and len(w) > 1][-3:]
            label_words = after if after else before
            label = " ".join(label_words)
            seen_n.add(val)
            numbers.append(f"{val} {label}".strip() if label else val)

    dates, seen_d = [], set()
    for u in utterances:
        for m in _DATE_PATTERN.finditer(u["text"]):
            val = m.group(0).strip()
            key = val.lower()
            if key not in seen_d and key not in _WEEKDAYS_MONTHS:
                seen_d.add(key)
                dates.append(val if any(c.isdigit() for c in val) else val.title())

    return numbers[:limit], dates[:limit]


_PRONOUN_CONTRACTIONS = frozenset(
    "i i'll i'm i've i'd we we'll we're we've we'd you you'll you're you've it it's".split()
)


def extract_technical_terms(utterances, exclude=(), limit=6):
    exclude_lower = {e.lower() for e in exclude}
    counts = Counter()
    for u in utterances:
        words = u["text"].split()
        for idx, w in enumerate(words):
            if idx == 0:
                continue
            cleaned = w.strip(".,!?;:\"'()")
            if (
                cleaned
                and cleaned[0].isupper()
                and len(cleaned) > 2
                and cleaned.lower() not in STOPWORDS
                and cleaned.lower() not in _PRONOUN_CONTRACTIONS
            ):
                counts[cleaned] += 1
    return [w for w, c in counts.most_common(limit * 3) if c >= 2 and w.lower() not in exclude_lower][:limit]


# =======================================================================
# Purpose V2: primary + secondary, from utterance-type mix, not raw TF-IDF
# =======================================================================

PURPOSE_CATEGORIES = {
    "Project status update": ["update", "progress", "status", "on track", "behind schedule", "checking in", "check-in", "standup", "currently", "so far"],
    "Release planning": ["launch", "ship date", "release date", "deadline", "readiness", "sign off", "sign-off", "gate", "target date", "timeline"],
    "Problem solving": ["problem", "issue", "bug", "blocker", "fix", "root cause", "workaround"],
    "Evaluation/testing session": ["test", "testing", "evaluate", "evaluation", "accuracy", "accurate", "recognize", "recognition", "benchmark"],
    "Technical review": ["review", "code review", "architecture", "deploy", "pull request", "codebase", "implementation"],
    "Brainstorming session": ["idea", "brainstorm", "what if", "options", "could we", "alternative"],
    "Interview": ["tell me about", "your experience", "walk me through", "background"],
}


def infer_purpose(text_lower, word_total, issues, actions, timeline, open_questions):
    scores = {}
    for cat, keywords in PURPOSE_CATEGORIES.items():
        hits = sum(text_lower.count(k) for k in keywords)
        scores[cat] = hits / max(word_total, 1)

    # Structural signals beyond keywords: lots of issues + actions + a
    # revised deadline strongly implies status-update-with-planning, even
    # if "update"/"launch" themselves are sparse in this particular wording.
    if issues:
        scores["Problem solving"] = scores.get("Problem solving", 0) + 0.003 * len(issues)
    if timeline:
        scores["Release planning"] = scores.get("Release planning", 0) + 0.004 * len(timeline)
    if actions and len(actions) >= 2:
        scores["Project status update"] = scores.get("Project status update", 0) + 0.002 * len(actions)

    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    ranked = [(c, s) for c, s in ranked if s > 0]
    if not ranked:
        return "General discussion", None, 0.3, []

    primary, primary_score = ranked[0]
    secondary = None
    if len(ranked) > 1 and ranked[1][1] >= primary_score * 0.4:
        secondary = ranked[1][0]

    evidence = [c for c in PURPOSE_CATEGORIES[primary] if c in text_lower][:3]
    confidence = min(0.95, 0.5 + primary_score * 20)
    return primary, secondary, confidence, evidence


def _join(items):
    items = list(items)
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    if len(items) == 2:
        return f"{items[0]} and {items[1]}"
    return f"{', '.join(items[:-1])}, and {items[-1]}"


def _with_article(phrase):
    return f"{'an' if phrase[:1].lower() in 'aeiou' else 'a'} {phrase}"


def compose_purpose(primary, secondary, topics):
    base = primary
    if secondary:
        base = f"{primary}, with a secondary focus on {secondary.lower()}"
    topic_str = _join(topics[:2])
    if topic_str:
        return f"{base}, centered on {topic_str}."
    return f"{base}."


# =======================================================================
# Takeaway synthesis: composed from structured items, not raw sentences
# =======================================================================


def extract_takeaways(utterances, centrality, issues, actions, timeline, open_questions, decisions, limit=7):
    takeaways = []

    for iss in issues:
        if iss["priority"] == "high":
            takeaways.append(f"{iss['evidence']} This was flagged as a high-priority issue.")
    for entry in timeline:
        if entry["type"] == "revised":
            orig = next((t for t in timeline if t["type"] == "original"), None)
            if orig:
                cond = f", conditional on {entry['condition']}" if entry["condition"] else ""
                takeaways.append(
                    f"The original {orig['date']} target is no longer considered on track; "
                    f"{entry['date']} has been proposed as the revised target{cond}."
                )
    for oq in open_questions[:2]:
        takeaways.append(f"Unresolved: {oq}")
    for d in decisions[:2]:
        takeaways.append(d["text"])

    takeaways = dedupe_by_similarity(takeaways, key=lambda t: t, threshold=0.55, limit=limit)

    if len(takeaways) < 3:
        decision_set = {d["text"].lower() for d in decisions}
        action_set = {a["task"].lower() for a in actions}
        scored = []
        for i, (u, c) in enumerate(zip(utterances, centrality)):
            if len(u["text"].split()) < 5:
                continue
            score = c
            if u["lower"] in decision_set:
                score += 0.3
            scored.append((score, u["text"]))
        scored.sort(key=lambda t: -t[0])
        fallback = dedupe_by_similarity([t for _, t in scored], key=lambda t: t, threshold=0.55, limit=limit - len(takeaways))
        takeaways = dedupe_by_similarity(takeaways + fallback, key=lambda t: t, threshold=0.55, limit=limit)

    return takeaways


