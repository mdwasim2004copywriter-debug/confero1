def compose_executive_summary(primary, secondary, topics, decisions, actions, issues, timeline, open_questions):
    described = _with_article(primary.lower())
    if secondary:
        described += f" with a focus on {secondary.lower()}"
    topic_str = _join(topics[:3])
    parts = [f"This was {described}, centered on {topic_str}." if topic_str else f"This was {described}."]

    high_issues = [i for i in issues if i["priority"] == "high"]
    if high_issues:
        parts.append(f"The main issue raised was: {high_issues[0]['evidence']}")
    if actions:
        parts.append(f"{len(actions)} action item{'s were' if len(actions) != 1 else ' was'} identified.")
    if timeline:
        revised = next((t for t in timeline if t["type"] == "revised"), None)
        if revised:
            parts.append(f"The timeline was revised, targeting {revised['date']}.")
    if open_questions:
        parts.append(f"{len(open_questions)} item{'s remain' if len(open_questions) != 1 else ' remains'} unresolved.")
    return " ".join(parts)


def compose_conclusion(issues, actions, timeline, open_questions, priority_relations):
    high_issues = [i for i in issues if i["priority"] == "high"]

    state_part = None
    if high_issues:
        state_part = f"The main blocker is: {high_issues[0]['evidence']}"
    elif issues:
        state_part = f"One notable issue was raised: {issues[0]['evidence']}"
    else:
        state_part = "No major blockers were identified."

    next_steps = None
    if actions:
        tasks = _join([a["task"].rstrip(".") for a in actions[:3]])
        next_steps = f"Next steps: {tasks}."

    timeline_part = None
    revised = next((t for t in timeline if t["type"] == "revised"), None)
    original = next((t for t in timeline if t["type"] == "original"), None)
    if revised and original:
        cond = f", conditional on {revised['condition']}" if revised["condition"] else ""
        timeline_part = f"The original {original['date']} target has been revised to {revised['date']}{cond}."
    elif revised:
        timeline_part = f"{revised['date']} is the proposed target."

    open_part = None
    if open_questions:
        open_part = f"Unresolved: {_join(open_questions[:2])}."

    return " ".join(p for p in [state_part, timeline_part, next_steps, open_part] if p)


# =======================================================================
# Validation layer (defense in depth -- classifiers should already exclude
# these, this is a final safety net so a regression can't silently regress
# past it)
# =======================================================================


def validate_state(decisions, actions, topics, open_questions):
    decisions = [d for d in decisions if not is_unresolved(d["text"].lower()) and not d["text"].strip().endswith("?")]
    actions = [a for a in actions if any(v in a["task"].lower() for v in ACTION_VERBS) or a["owner"] != "Unknown"]
    topics = [t for t in topics if not _is_low_quality_phrase(t.lower())]
    return decisions, actions, topics, open_questions


